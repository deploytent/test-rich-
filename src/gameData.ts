// ==================== HELPERS FOR DYNAMIC MATH GENERATORS ====================
function shuffleArray<T>(arr: T[], rng: () => number = Math.random): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function buildUniqueNumericOptions(
  correctVal: number,
  candidatePool: number[],
  format: (n: number) => string,
  rng: () => number = Math.random
): { options: string[]; correctIndex: number } {
  const distractors: number[] = [];
  for (const cand of shuffleArray(candidatePool, rng)) {
    if (cand !== correctVal && cand > 0 && !distractors.includes(cand)) {
      distractors.push(cand);
      if (distractors.length === 3) break;
    }
  }
  let offset = 1;
  while (distractors.length < 3) {
    const fallback = correctVal + offset * 5;
    if (fallback !== correctVal && !distractors.includes(fallback)) {
      distractors.push(fallback);
    }
    offset++;
  }
  const raw = shuffleArray([correctVal, ...distractors], rng);
  const correctIndex = raw.indexOf(correctVal);
  return {
    options: raw.map(format),
    correctIndex,
  };
}

/**
 * Dynamic Math Generator for "แก้โจทย์ไว ลด 20%" (Buy Discount)
 * Generates brand-new randomized numbers every time it is called.
 */
export function generateDynamicBuyDiscountPuzzle(
  rng: () => number = Math.random
): BuyDiscountPuzzle {
  const variant = Math.floor(rng() * 4);
  const uid = `dyn-disc-${Date.now()}-${Math.floor(rng() * 10000)}`;

  // 1. Dynamic Mode (ฐานนิยม) from 5-7 numbers
  if (variant === 0) {
    const len = 5 + Math.floor(rng() * 3); // 5, 6, or 7
    const pool = shuffleArray([1, 2, 3, 4, 5, 6, 7, 8, 9], rng);
    const modeNum = pool[0];
    const modeCount = len >= 7 ? 3 : len === 6 ? 3 : 2;
    const nums: number[] = Array(modeCount).fill(modeNum);
    // Ensure remaining numbers appear strictly fewer times than modeCount
    let idx = 1;
    while (nums.length < len) {
      nums.push(pool[idx]);
      idx++;
    }
    const sequence = shuffleArray(nums, rng);
    const { options, correctIndex } = buildUniqueNumericOptions(
      modeNum,
      [pool[1], pool[2], pool[3], pool[4], modeNum + 1, Math.max(1, modeNum - 1)],
      (n) => `${n}`,
      rng
    );

    return {
      id: uid,
      prompt: `ข้อมูลชุดนี้: ${sequence.join(', ')} ฐานนิยม (Mode) คือเลขใด?`,
      options,
      correctIndex,
      explanation: `เลข ${modeNum} ปรากฏบ่อยที่สุด (${modeCount} ครั้ง) จึงเป็นฐานนิยม`,
    };
  }

  // 2. Dynamic Relative Frequency (%) with clean integer division
  if (variant === 1) {
    const pairs: [number, number[]][] = [
      [20, [15, 20, 25, 30, 35, 40, 45, 55, 60]],
      [25, [12, 16, 20, 24, 28, 32, 36, 44, 48]],
      [30, [10, 20, 30, 40, 50, 60, 70]],
      [40, [15, 20, 25, 30, 35, 45, 55, 65]],
      [45, [20, 40, 60, 80]],
      [50, [12, 14, 18, 22, 24, 28, 34, 36, 42]],
      [60, [15, 20, 25, 30, 35, 45, 55, 65]],
      [80, [15, 20, 25, 30, 35, 40, 45, 55]],
    ];
    const [total, pctChoices] = pairs[Math.floor(rng() * pairs.length)];
    const pct = pctChoices[Math.floor(rng() * pctChoices.length)];
    const freq = Math.round((total * pct) / 100);
    const { options, correctIndex } = buildUniqueNumericOptions(
      pct,
      [pct - 10, pct - 5, pct + 5, pct + 10, pct + 15, Math.max(5, pct - 15)],
      (n) => `${n}%`,
      rng
    );

    return {
      id: uid,
      prompt: `ความถี่ ${freq} จากข้อมูลทั้งหมด ${total} คิดเป็นความถี่สัมพัทธ์กี่เปอร์เซ็นต์?`,
      options,
      correctIndex,
      explanation: `(${freq} ÷ ${total}) × 100 = ${pct}%`,
    };
  }

  // 3. Dynamic Pie Chart Central Angle (p% * 3.6 deg)
  if (variant === 2) {
    const pctOptions = [10, 15, 20, 25, 30, 35, 40, 45, 50];
    const pct = pctOptions[Math.floor(rng() * pctOptions.length)];
    const angle = Math.round(pct * 3.6);
    const { options, correctIndex } = buildUniqueNumericOptions(
      angle,
      [angle - 36, angle - 18, angle + 18, angle + 36, angle + 54, pct * 2],
      (n) => `${n}°`,
      rng
    );

    return {
      id: uid,
      prompt: `ในแผนภูมิรูปวงกลม ส่วนที่คิดเป็น ${pct}% จะมีขนาดมุมที่จุดศูนย์กลางกี่องศา?`,
      options,
      correctIndex,
      explanation: `${pct}% ของ 360° = (${pct} ÷ 100) × 360° = ${angle}°`,
    };
  }

  // 4. Dynamic Missing Percentage in Pie Chart (sum = 100%)
  const p1 = (2 + Math.floor(rng() * 5)) * 10; // 20..60
  const maxP2 = Math.min(50, 90 - p1);
  const stepsP2 = Math.max(1, Math.floor((maxP2 - 10) / 5));
  const p2 = 10 + Math.floor(rng() * stepsP2) * 5;
  const missing = 100 - p1 - p2;
  const { options, correctIndex } = buildUniqueNumericOptions(
    missing,
    [missing - 10, missing - 5, missing + 5, missing + 10, missing + 15],
    (n) => `${n}%`,
    rng
  );

  return {
    id: uid,
    prompt: `แผนภูมิรูปวงกลมมี 3 ส่วน: ส่วนแรก ${p1}% ส่วนที่สอง ${p2}% ส่วนที่สามต้องมีค่ากี่เปอร์เซ็นต์จึงจะครบ 100%?`,
    options,
    correctIndex,
    explanation: `100% - ${p1}% - ${p2}% = ${missing}%`,
  };
}

